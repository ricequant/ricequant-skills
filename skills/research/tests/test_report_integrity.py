    def test_failed_or_empty_announcement_cannot_display_summary(self):
        announcement = dict(title="2024年年度报告", announcement_link="https://example.test/report.pdf",
                            info_date="2025-04-03", info_type="定期报告")
        for fetch, extract, raw in (
            ("network_error:ConnectionError", "fetch_failed", ""),
            ("ok", "pdf_parse_failed:ValueError", ""),
            ("ok", "ok", ""),
            ("network_error:ConnectionError", "fetch_failed", "old cached text"),
            ("", "", "source without confirmed extraction status"),
        ):
            with self.subTest(fetch=fetch, extract=extract):
                record = dict(announcement, fetch_status=fetch, extract_status=extract,
                              raw_sections={"outlook": raw},
                              summaries={"outlook": "DO_NOT_DISPLAY"})
                section = PREVIEW.build_announcement_section([announcement], [record], [])
                self.assertNotIn("DO_NOT_DISPLAY", section)
                self.assertNotIn("已提炼关键片段", section)
                self.assertIn(announcement["announcement_link"], section)

    def test_partial_source_only_displays_supported_sections(self):
        record = dict(fetch_status="ok", extract_status="partial",
                      raw_sections={"outlook": "source outlook", "risk_warning": ""},
                      summaries={"outlook": "supported conclusion", "risk_warning": "invented risk"})
        for mod in (PREVIEW, ANALYSIS):
            with self.subTest(module=mod.__name__):
                self.assertEqual(mod.extract_section_display_text(record, "outlook"), "supported conclusion")
                self.assertEqual(mod.extract_section_display_text(record, "risk_warning"), "")
                self.assertEqual(mod.extract_section_display_text(
                    {"sections": {"outlook": "legacy summary"}}, "outlook"), "legacy summary")

    def test_analysis_distinguishes_source_status_from_summary_availability(self):
        record = dict(fetch_status="ok", extract_status="ok", raw_sections={"outlook": "source"},
                      summaries={"outlook": "verified summary"})
        self.assertEqual(ANALYSIS.announcement_status_label(record), "已提炼关键片段")
        failed = dict(record, fetch_status="network_error", extract_status="fetch_failed")
        self.assertEqual(ANALYSIS.extract_section_display_text(failed, "outlook"), "")
        self.assertNotIn("已提炼", ANALYSIS.announcement_status_label(failed))
        unfinished = dict(record, summaries={"outlook": ""})
        self.assertEqual(ANALYSIS.announcement_status_label(unfinished), "正文已提取，摘要未完成")
        empty_source = dict(record, raw_sections={"outlook": ""})
        self.assertEqual(ANALYSIS.extract_section_display_text(empty_source, "outlook"), "")
        self.assertNotIn("已提炼", ANALYSIS.announcement_status_label(empty_source))
        malformed_source = dict(record, raw_sections=["not a section mapping"])
        self.assertNotIn("已提炼", ANALYSIS.announcement_status_label(malformed_source))

    def run_thesis(self, announcement_payload):
        with tempfile.TemporaryDirectory() as directory:
            folder = Path(directory)
            if announcement_payload is not None:
                (folder / "announcement_raw.json").write_text(json.dumps(announcement_payload), encoding="utf-8")
            output = folder / "report.md"
            argv = ["generate_report.py", "--stock", STOCK, "--company", "合成测试公司",
                    "--data-dir", str(folder), "--report-date", CUTOFF.isoformat(),
                    "--output", str(output), "--no-render"]
            with patch.object(sys, "argv", argv):
                THESIS.main()
            return output.read_text(encoding="utf-8")

    def test_missing_failed_and_ambiguous_empty_announcements(self):
        for payload, expected in (
            (None, "公告数据未获取"),
            ([], "公告输入为空"),
            ({"status": "error", "error": "request failed", "data": []}, "公告采集失败"),
            ({"success": False, "data": []}, "公告采集失败"),
        ):
            with self.subTest(payload=payload):
                report = self.run_thesis(payload)
                self.assertIn(expected, report)
                self.assertNotIn("未识别到", report)
                self.assertNotIn("筛选出 0 条", report)

    def test_successful_empty_announcement_query_is_identified(self):
        report = self.run_thesis({"status": "ok", "data": []})
        self.assertIn("公告查询返回零条记录", report)
        self.assertNotIn("公告数据未获取", report)
        self.assertNotIn("最近 30 天未识别到", report)

    def test_catalysts_only_include_report_date_window(self):
        rows = [dict(order_book_id=STOCK, title=label + "回购公告", info_date=when)
                for label, when in (("old", "2025-03-10"), ("start", "2025-03-11"),
                                    ("today", "2025-04-10"), ("future", "2025-04-11"))]
        selected = THESIS.extract_catalysts(rows, STOCK, CUTOFF)
        self.assertEqual({item.title for item in selected}, {"start回购公告", "today回购公告"})
        report = self.run_thesis(rows)
        self.assertNotIn("old回购公告", report)
        self.assertNotIn("future回购公告", report)
        self.assertIn("today回购公告", report)

    def test_factor_history_needs_multiple_dates_and_shows_actual_coverage(self):
        row = dict(order_book_id=STOCK, date="2025-04-09", pe_ratio=4)
        future = dict(row, date="2025-04-11", pe_ratio=100)
        for rows in ([row], [row, dict(row, pe_ratio=5)], [row, future]):
            with self.subTest(rows=rows):
                text = THESIS.factor_range_text(rows, STOCK, "pe_ratio", CUTOFF, 1)
                self.assertIn("历史数据不足", text)
                self.assertIn("2025-04-09", text)
        text = THESIS.factor_range_text(
            [row, dict(row, date="2025-04-10", pe_ratio=6), future], STOCK, "pe_ratio", CUTOFF, 1)
        for expected in ("4.0x", "6.0x", "2025-04-09", "2025-04-10", "2 个日期"):
            self.assertIn(expected, text)
        self.assertNotIn("100.0x", text)

    def test_consensus_annual_years_are_explicit_and_not_field_names(self):
        snapshot = dict(report_year_t="2024", date="2025-04-10",
                        comp_con_operating_revenue_t1=100e8, comp_con_net_profit_t1=10e8,
                        comp_con_operating_revenue_t2=110e8, comp_con_net_profit_t2=11e8,
                        comp_con_operating_revenue_t3=120e8, comp_con_net_profit_t3=12e8)
        section = PREVIEW.build_expectation_section(snapshot, {"count": 0}, {"count": 0})
        for year in (2025, 2026, 2027):
            self.assertIn(str(year), section)
        for internal in ("t1/t2/t3", "forward buckets", "comp_con_"):
            self.assertNotIn(internal, section)
        self.assertIn("年度", section)
        for base in (None, "invalid", "0000", "1000", "9997", "9999"):
            unknown = dict(snapshot, report_year_t=base)
            text = PREVIEW.build_expectation_section(unknown, {"count": 0}, {"count": 0})
            self.assertIn("年份未验证", text)
            self.assertNotIn(str(date.today().year + 3), text)

