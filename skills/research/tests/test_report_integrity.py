    def test_idea_rejects_internal_terms_in_model_writeback(self):
        summaries = {key: "客户可读的研究说明，ROE 与 PE 用于对比。" for key in IDEA.SUMMARY_KEYS}
        self.assertEqual(IDEA.require_summaries({"summaries": summaries}), summaries)
        for internal in ("传入date=2025-04-10", "缺失info_date字段", "未做web_search验证", "stock_pool", "input.json文件", "由LLM回写"):
            with self.subTest(internal=internal):
                with self.assertRaisesRegex(ValueError, "内部"):
                    IDEA.require_summaries({"summaries": dict(summaries, appendix=internal)})

    def test_named_research_wrapper_preserves_records_and_summaries(self):
        row = dict(order_book_id=STOCK, report_title="合成公司年报点评",
                   summaries={"core_view": "model-written explanation"})
        for mod in (PREVIEW, ANALYSIS, COVERAGE):
            for payload in ([row], {"data": [row]}, {"data": row}, row, {"records": [row]}):
                with self.subTest(module=mod.__name__, payload=payload):
                    self.assertEqual(mod.extract_named_records(payload, "records"), [row])
            self.assertEqual(mod.extract_named_records({"records": []}, "records"), [])


