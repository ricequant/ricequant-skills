"""Observable report regressions; no API, network or market credentials required."""
import importlib.util
import json
from pathlib import Path
import sys
import tempfile
import unittest
import subprocess
from unittest.mock import patch
from datetime import date, datetime, timedelta


ROOT = Path(__file__).resolve().parents[1]
STOCK = "SYNTHETIC"
CUTOFF = date(2025, 4, 10)


def load_skill(name):
    spec = importlib.util.spec_from_file_location(
        "integrity_" + name.replace("-", "_"), ROOT / name / "scripts/generate_report.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


PREVIEW = load_skill("earnings-preview")
THESIS = load_skill("thesis-tracker")
IDEA = load_skill("idea-generation")
ANALYSIS = load_skill("earnings-analysis")
COVERAGE = load_skill("initiating-coverage")


class ReportIntegrityTests(unittest.TestCase):
    def test_rendered_customer_document_preserves_facts_without_technical_labels(self):
        with tempfile.TemporaryDirectory() as directory:
            folder=Path(directory)
            markdown=folder/'sample.md'
            markdown.write_text('# 合成研究报告\n\n- 报告日期：2025-04-10\n\n## 财务\n\n| 指标 | 数值 |\n| --- | --- |\n| 净利润同比 | -100%（亏损扩大） |\n\n*数据来源：RQData，置信度5*\n')
            output=folder/'report.html'
            result=subprocess.run([sys.executable,str(ROOT/'report-renderer/scripts/render_report.py'),str(markdown),str(output)],capture_output=True,text=True)
            self.assertEqual(result.returncode,0,result.stderr)
            html=output.read_text()
            for fact in ('2025-04-10','合成研究报告','亏损扩大','数据来源：RQData','<table>'):
                self.assertIn(fact,html)
            for internal in ('Generated by','scripts/render_report.py','RQ Research Markdown','Standalone HTML','RQ Report Renderer','由 Markdown 研究报告自动渲染'):
                self.assertNotIn(internal,html)

    def test_announcement_risk_extract_prefers_substantive_section(self):
        # The extractor uses a sibling generate_report import; run each in its
        # actual script directory so the test does not mix skill modules.
        for skill in ('earnings-preview', 'earnings-analysis'):
            code = '''
import sys, types
# This test exercises only text parsing, without an HTTP client or requests.
sys.modules['requests'] = types.ModuleType('requests')
from extract_announcements import extract_sections, build_raw_sections
text = '重大风险提示本公司已在未来发展章节阐述公司可能面对的风险，敬请投资者予以关注。风险提示□适用√不适用4、产品情况无关内容。(四)可能面对的风险√适用□不适用一是宏观经济风险；二是安全风险。(五)其他公司治理无关内容。'
for function in (extract_sections, build_raw_sections):
    risk = function('2024年年度报告', '定期报告', text)['risk_warning']
    assert '宏观经济风险' in risk and '安全风险' in risk, risk
    assert '产品情况' not in risk and '公司治理' not in risk, risk
    empty = function('2024年年度报告', '定期报告', '风险提示□适用√不适用4、产品情况无关内容。')['risk_warning']
    assert not empty, empty
'''
            with self.subTest(skill=skill):
                result = subprocess.run([sys.executable, '-c', code], cwd=ROOT/skill/'scripts', capture_output=True, text=True)
                self.assertEqual(result.returncode, 0, result.stderr)

    def test_coverage_consensus_timestamp_selection_and_future_creation(self):
        rows = [dict(date="2025-04-09", create_tm="2025-04-09 16:33:12", con_targ_price=12),
                dict(date="2025-04-10", create_tm="2025-04-10 16:33:12", con_targ_price=13),
                dict(date="2025-04-10", create_tm="2025-04-10 16:33:13", con_targ_price=14),
                dict(date="2025-04-10", create_tm="2025-04-11 08:00:00", con_targ_price=999)]
        self.assertEqual(COVERAGE.choose_latest_record_by_cutoff(rows, CUTOFF)['con_targ_price'], 14)
        self.assertEqual(COVERAGE.parse_timestamp("2025-04-10"), datetime(2025, 4, 10))
        self.assertEqual(COVERAGE.parse_timestamp("2025-04-10T16:33:12.123"), datetime(2025, 4, 10, 16, 33, 12, 123000))

    def test_unknown_consensus_year_is_not_inferred_from_runtime(self):
        for mod in (COVERAGE, ANALYSIS):
            for base in (None, "", "invalid", "0", "0000", "1000", "9997", "9999"):
                with self.subTest(module=mod.__name__, base=base):
                    self.assertEqual(mod.consensus_year_map(dict(report_year_t=base, comp_con_net_profit_t1=100)), {})
            self.assertEqual(mod.consensus_year_map(dict(report_year_t="2024", comp_con_net_profit_t1=100))[2025]['profit'], 100)

    def test_coverage_cli_displays_consensus_and_missing_risk_evidence(self):
        with tempfile.TemporaryDirectory() as directory:
            folder = Path(directory)
            financial = dict(order_book_id=STOCK, quarter="2024q4", info_date="2025-03-15", revenue=100, net_profit=10)
